-- Universal installer licensing: plans, installations, one-time codes, orders,
-- entitlements, audit log, owner sessions and rate limits.
--
-- Run once in the Supabase SQL editor (or `supabase db push`) BEFORE deploying
-- the storefront version that serves /api/v2/*. It only creates new objects;
-- no existing table or row is modified. Safe to re-run.
--
-- Access model: these tables live in the private avara_store schema, which is
-- not exposed through the Supabase Data API. Row Level Security is enabled with
-- no policies, and every privilege is revoked from anon/authenticated/public,
-- so only the storefront server (connecting with the private database URL
-- stored in Render) can read or write them.
begin;

create table if not exists avara_store.plans (
    id text primary key,
    name text not null,
    tier text not null check (tier in ('basic', 'pro')),
    price_inr integer not null check (price_inr >= 0),
    term_days integer not null check (term_days > 0),
    six_month smallint not null default 0 check (six_month in (0, 1)),
    active smallint not null default 1 check (active in (0, 1)),
    sort integer not null default 0,
    legacy_label text
);

insert into avara_store.plans (id, name, tier, price_inr, term_days, six_month, active, sort, legacy_label) values
    ('basic', 'Basic', 'basic', 150, 30, 0, 1, 10, 'Basic — ₹150/month'),
    ('pro', 'Pro', 'pro', 200, 30, 0, 1, 20, 'Pro — ₹200/month'),
    ('six_month_basic', '6-Month Basic', 'basic', 1000, 180, 1, 1, 30, '6-Month Basic — ₹1,000/6 months'),
    ('six_month_pro', '6-Month Pro', 'pro', 1400, 180, 1, 1, 40, '6-Month Pro — ₹1,400/6 months')
on conflict (id) do nothing;

-- One row per installed copy. Only a SHA-256 of the installation secret is kept.
create table if not exists avara_store.app_installations (
    id text primary key,
    token_hash text not null unique,
    legacy_code text not null unique,
    platform text not null default 'unknown',
    app_version text,
    user_id bigint references avara_store.users(id),
    created bigint not null,
    last_seen bigint not null
);

-- One-time codes. Only an HMAC of the code and a display hint (last 4 chars)
-- are stored; the code itself is re-derivable only with the installation secret.
create table if not exists avara_store.activation_codes (
    code_hash text primary key,
    installation_id text not null references avara_store.app_installations(id),
    nonce text not null,
    hint text not null,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'superseded')),
    created bigint not null,
    expires_at bigint not null,
    used_at bigint
);
create index if not exists activation_codes_installation_idx on avara_store.activation_codes (installation_id, created);

create table if not exists avara_store.license_orders (
    id bigint generated by default as identity primary key,
    installation_id text not null references avara_store.app_installations(id),
    plan_id text not null references avara_store.plans(id),
    price_inr integer not null,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'superseded')),
    code_hash text not null unique references avara_store.activation_codes(code_hash),
    created bigint not null,
    decided_at bigint,
    decided_by text,
    payment_method text not null default 'manual',
    payment_reference text,
    note text
);
create index if not exists license_orders_installation_idx on avara_store.license_orders (installation_id, id);
create index if not exists license_orders_status_idx on avara_store.license_orders (status, id);

-- Current plan per installation. Legacy activations are keyed by legacy_code
-- until the customer's universal app links them to its installation id.
create table if not exists avara_store.entitlements (
    id bigint generated by default as identity primary key,
    installation_id text unique references avara_store.app_installations(id),
    legacy_code text unique,
    plan_id text not null references avara_store.plans(id),
    tier text not null check (tier in ('basic', 'pro')),
    six_month smallint not null default 0 check (six_month in (0, 1)),
    state text not null check (state in ('active', 'paused', 'cancelled')),
    starts_at bigint not null,
    expires_at bigint not null,
    paused_at bigint,
    source_order_id bigint references avara_store.license_orders(id),
    legacy_order_id bigint references avara_store.orders(id),
    updated_at bigint not null,
    check (installation_id is not null or legacy_code is not null)
);

create table if not exists avara_store.audit_log (
    id bigint generated by default as identity primary key,
    at bigint not null,
    actor text not null,
    action text not null,
    target text,
    detail text,
    ip text
);
create index if not exists audit_log_at_idx on avara_store.audit_log (at);

-- The audit log is append-only, even for the table owner.
create or replace function avara_store.audit_log_append_only() returns trigger
language plpgsql set search_path = pg_catalog as $$
begin
    raise exception 'avara_store.audit_log is append-only';
end;
$$;
drop trigger if exists audit_log_append_only on avara_store.audit_log;
create trigger audit_log_append_only before update or delete or truncate on avara_store.audit_log
    for each statement execute function avara_store.audit_log_append_only();

create table if not exists avara_store.owner_sessions (
    token_hash text primary key,
    created bigint not null,
    expires bigint not null,
    ip text
);

create table if not exists avara_store.rate_limits (
    bucket text not null,
    window_start bigint not null,
    hits integer not null,
    primary key (bucket, window_start)
);

alter table avara_store.plans enable row level security;
alter table avara_store.app_installations enable row level security;
alter table avara_store.activation_codes enable row level security;
alter table avara_store.license_orders enable row level security;
alter table avara_store.entitlements enable row level security;
alter table avara_store.audit_log enable row level security;
alter table avara_store.owner_sessions enable row level security;
alter table avara_store.rate_limits enable row level security;

revoke all on avara_store.plans, avara_store.app_installations, avara_store.activation_codes,
    avara_store.license_orders, avara_store.entitlements, avara_store.audit_log,
    avara_store.owner_sessions, avara_store.rate_limits
    from public, anon, authenticated;
revoke all on all sequences in schema avara_store from public, anon, authenticated;
revoke all on function avara_store.audit_log_append_only() from public, anon, authenticated;

commit;
