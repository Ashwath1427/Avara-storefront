-- Customer emails log + a readable customer overview for the Supabase dashboard.
-- Run after 001 and 002. Creates new objects only; safe to re-run.
--
-- In Supabase: Table Editor -> schema "avara_store" -> customer_overview (one row per
-- computer: who, which plan, status, expiry, latest order) and email_log (every email sent).
begin;

create table if not exists avara_store.email_log (
    id bigint generated by default as identity primary key,
    at bigint not null,
    user_id bigint references avara_store.users(id),
    to_email text not null,
    kind text not null,
    subject text not null,
    status text not null check (status in ('sent', 'failed', 'not_configured')),
    error text,
    ref text
);
create index if not exists email_log_at_idx on avara_store.email_log (at);
alter table avara_store.email_log enable row level security;
revoke all on avara_store.email_log from public, anon, authenticated;

create or replace view avara_store.customer_overview with (security_invoker = true) as
select
    u.name                                   as customer_name,
    u.email                                  as customer_email,
    i.id                                     as installation_id,
    i.platform,
    i.app_version,
    to_timestamp(i.created)                  as first_seen,
    to_timestamp(i.last_seen)                as last_seen,
    p.name                                   as plan,
    case when e.state = 'active' and e.expires_at <= extract(epoch from now()) then 'expired' else e.state end as plan_status,
    to_timestamp(e.expires_at)               as plan_expires,
    lo.id                                    as latest_order_id,
    lp.name                                  as latest_order_plan,
    lo.price_inr                             as latest_order_price_inr,
    lo.status                                as latest_order_status,
    to_timestamp(lo.created)                 as latest_order_at
from avara_store.app_installations i
left join avara_store.users u on u.id = i.user_id
left join avara_store.entitlements e on e.installation_id = i.id
left join avara_store.plans p on p.id = e.plan_id
left join lateral (
    select o.* from avara_store.license_orders o where o.installation_id = i.id order by o.id desc limit 1
) lo on true
left join avara_store.plans lp on lp.id = lo.plan_id;

revoke all on avara_store.customer_overview from public, anon, authenticated;

commit;

