-- Run in Supabase SQL Editor before pointing Render at this database.
begin;
create schema if not exists avara_store;
revoke all on schema avara_store from public, anon, authenticated, service_role;

create table if not exists avara_store.users (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null unique,
    salt bytea not null,
    password bytea not null
);
create table if not exists avara_store.sessions (
    token_hash text primary key,
    user_id bigint not null references avara_store.users(id),
    expires bigint not null
);
create table if not exists avara_store.orders (
    id bigint generated by default as identity primary key,
    user_id bigint not null references avara_store.users(id),
    plan text not null,
    addon text not null,
    terms_version text not null,
    created bigint not null,
    status text not null default 'pending',
    approved_at bigint,
    delivery_email_status text not null default 'not_sent',
    platform text not null default 'windows' check(platform in ('windows','mac'))
);
alter table avara_store.orders add column if not exists platform text not null default 'windows';
alter table avara_store.orders add column if not exists deleted_at bigint;
create index if not exists avara_orders_customer_idx on avara_store.orders(user_id, id);
create table if not exists avara_store.order_email (
    order_id bigint primary key references avara_store.orders(id),
    status text not null,
    created bigint not null
);
create table if not exists avara_store.reviews (
    id bigint generated by default as identity primary key,
    user_id bigint not null references avara_store.users(id),
    body text not null,
    created bigint not null,
    status text not null default 'pending'
);
create table if not exists avara_store.installations (
    code text primary key,
    order_id bigint not null unique references avara_store.orders(id),
    plan text not null check(plan in ('basic','pro')),
    expires bigint not null,
    state text not null default 'active' check(state in ('active','paused','cancelled')),
    paused_at bigint
);
alter table avara_store.installations add column if not exists state text not null default 'active';
alter table avara_store.installations add column if not exists paused_at bigint;
create table if not exists avara_store.reward_locks (
    id text primary key,
    pin_hash text not null unique,
    clues text not null,
    consumed integer not null default 0
);
create table if not exists avara_store.reward_claims (
    code text primary key,
    user_id bigint not null unique references avara_store.users(id),
    lock_id text not null unique references avara_store.reward_locks(id),
    created bigint not null
);
create table if not exists avara_store.reward_attempts (
    user_id bigint not null references avara_store.users(id),
    created bigint not null
);
-- Defense in depth for the private schema. The server connects as the table owner.
alter table avara_store.users enable row level security;
alter table avara_store.sessions enable row level security;
alter table avara_store.orders enable row level security;
alter table avara_store.reviews enable row level security;
alter table avara_store.order_email enable row level security;
alter table avara_store.installations enable row level security;
alter table avara_store.reward_locks enable row level security;
alter table avara_store.reward_claims enable row level security;
alter table avara_store.reward_attempts enable row level security;
revoke all on all tables in schema avara_store from public, anon, authenticated, service_role;
revoke all on all sequences in schema avara_store from public, anon, authenticated, service_role;
commit;
