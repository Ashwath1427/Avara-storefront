def platform_release_enabled(platform: str) -> bool:
    release = PART_RELEASE.get("platforms", {}).get(platform)
    return bool(release and release.get("enabled", True))


def platform_release_message(platform: str) -> str:
    release = PART_RELEASE.get("platforms", {}).get(platform, {})
    return release.get("message") or "This platform release is temporarily unavailable."


def plan_filename(plan: str, platform: str = 'windows'):
    if installer_downloads():
        key = "mac-arm64" if platform == "mac" else platform
        if key not in INSTALLER_FILES:
            raise HTTPException(400, "Choose Windows or Mac Apple Silicon.")
        return INSTALLER_FILES[key][0]
    if platform not in ('windows', 'mac'):
        raise HTTPException(400, 'Choose Windows or Mac.')
    return f'avara-{plan_slug(plan)}{ "-mac" if platform == "mac" else ""}.zip'


def customer_installer_filename(plan, platform):
    """Name the download for its paid plan without duplicating stored app engines."""
    edition = plan_slug(plan)
    term = '6month-' if plan.startswith(('6-Month Basic', '6-Month Pro', 'AVARA 6-Month Plus')) else ''
    suffix = 'windows-setup.exe' if platform == 'windows' else platform + '.dmg'
    if platform not in INSTALLER_FILES:
        raise HTTPException(400, 'Choose a supported operating system and architecture.')
    return f'AVARA-{INSTALLER_VERSION}-{term}{edition}-{suffix}'


