@app.post('/api/admin/releases/publish-catalog')
def publish_release_catalog(request: Request):
    owner_session(request)
    if not installer_downloads() or not PART_RELEASE.get('enabled'):
        raise HTTPException(409, 'Native installer delivery must be enabled first.')
    for platform in INSTALLER_FILES:
        if not plan_bundle_ready('Basic', platform):
            raise HTTPException(409, 'A required installer part is missing. Catalog was not published.')
    upload = storage_request('Basic', method='POST', object_name='release-catalog.json')
    if not upload:
        raise HTTPException(503, 'Private release storage is not configured.')
    upload.data = json.dumps(release_catalog(), indent=2).encode('utf-8')
    upload.add_header('Content-Type', 'application/json')
    upload.add_header('x-upsert', 'true')
    try:
        with urllib.request.urlopen(upload, timeout=30) as result:
            result.read(4096)
    except (HTTPError, OSError, ValueError):
        raise HTTPException(503, 'Could not sync the private release catalog. Try again.')
    return {'message': 'Release catalog synced to Supabase: 8 plan downloads using shared installer parts.'}


def plan_bundle(plan: str, platform: str = 'windows'):
    slug = plan_slug(plan)
    plan_filename(plan, platform)
    suffix = '_MAC' if platform == 'mac' else ''
    configured = '' if installer_downloads() else os.getenv(f'AVARA_{slug.upper()}{suffix}_ZIP', '').strip()
    return Path(configured) if configured else ROOT / 'deliverables' / plan_filename(plan, platform)


def storage_request(plan: str, method='GET', platform: str = 'windows', object_name: str | None = None):
    url = os.getenv('SUPABASE_URL', '').strip().rstrip('/')
    key = os.getenv('SUPABASE_SERVICE_ROLE_KEY', '').strip()
    bucket = os.getenv('AVARA_RELEASE_BUCKET', 'avara-releases').strip()
    if not url or not key or not bucket:
        return None
    slug = plan_slug(plan)
    filename = plan_filename(plan, platform)
    suffix = '_MAC' if platform == 'mac' else ''
    if object_name is None:
        object_name = filename if installer_downloads() else os.getenv(f'AVARA_{slug.upper()}{suffix}_STORAGE_OBJECT', filename).strip()
    if not object_name:
        return None
    headers = {'apikey': key, 'Cache-Control': 'no-store'}
    if not key.startswith('sb_secret_'):
        headers['Authorization'] = 'Bearer ' + key
    path = '/'.join(quote(part, safe='') for part in object_name.split('/'))
    object_route = 'object' if method == 'POST' else 'object/authenticated'
    return urllib.request.Request(
        f'{url}/storage/v1/{object_route}/{quote(bucket, safe="")}/{path}',
        headers=headers,
        method=method,
    )


def installer_parts(platform):
    if installer_downloads() and PART_RELEASE.get("enabled"):
        return PART_RELEASE.get("platforms", {}).get(platform)
    return None


def stream_installer_parts(requests, metadata, first_response):
    response = first_response
    complete = hashlib.sha256()
    try:
        for index, (request, part) in enumerate(zip(requests, metadata["parts"], strict=True)):
            if index:
                response = urllib.request.urlopen(request, timeout=30)
            digest = hashlib.sha256()
            size = 0
            pending = None
            try:
                while chunk := response.read(1024 * 1024):
                    size += len(chunk)
                    if size > part["size"]:
                        raise OSError("Release part exceeded its expected size")
                    digest.update(chunk)
                    complete.update(chunk)
                    if pending is not None:
                        yield pending
                    pending = chunk
                if size != part["size"] or digest.hexdigest() != part["sha256"]:
                    raise OSError("Release part integrity check failed")
                if index == len(metadata["parts"]) - 1 and complete.hexdigest() != metadata["sha256"]:
                    raise OSError("Release integrity check failed")
                if pending is not None:
                    yield pending
            finally:
                response.close()
                response = None
    finally:
        if response is not None:
            response.close()


def plan_bundle_ready(plan: str, platform: str = 'windows'):
    if installer_downloads() and platform == "mac":
        return plan_bundle_ready(plan, "mac-arm64")
    if plan_bundle(plan, platform).is_file():
        return True
    metadata = installer_parts(platform)
    if metadata:
        cached = _release_ready_cache.get((platform, metadata["sha256"]))
        if cached and cached[0] > time.monotonic():
            return cached[1]
        ready = True
        for part in metadata["parts"]:
            request = storage_request(plan, "HEAD", platform, object_name=part["name"])
            if not request:
                ready = False
                break
            try:
                with urllib.request.urlopen(request, timeout=8) as response:
                    if int(response.headers.get("Content-Length", -1)) != part["size"]:
                        ready = False
                        break
            except (HTTPError, OSError, ValueError):
                ready = False
                break
        _release_ready_cache[(platform, metadata["sha256"])] = (time.monotonic() + 60, ready)
        return ready
    request = storage_request(plan, 'HEAD', platform)
    if not request:
        return False
    try:
        with urllib.request.urlopen(request, timeout=8):
            return True
    except (HTTPError, OSError, ValueError):
        return False


