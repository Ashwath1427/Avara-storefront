@app.get('/api/order/{order_id}/download')
def download_order(order_id: int, request: Request, platform: str | None = None, architecture: str | None = None):
    user_id, _, _ = session(request)
    with db() as con:
        row = con.execute('SELECT plan,status,platform FROM orders WHERE id=? AND user_id=? AND deleted_at IS NULL', (order_id, user_id)).fetchone()
    if not row:
        raise HTTPException(404, 'Order not found.')
    if row[1] != 'approved':
        raise HTTPException(403, 'This order is not ready for download yet.')
    if platform is not None and platform != row[2]:
        raise HTTPException(403, 'This order is for a different operating system.')
    platform = row[2]
    plan = row[0]
    media_type = "application/zip"
    if installer_downloads():
        if platform == "mac":
            if architecture not in (None, "arm64"):
                raise HTTPException(400, "This release supports Apple Silicon Macs only.")
            platform = "mac-arm64"
        media_type = INSTALLER_FILES[platform][1]
    bundle = plan_bundle(plan, platform)
    if bundle.is_file():
        return FileResponse(bundle, filename=customer_installer_filename(plan, platform) if installer_downloads() else plan_filename(plan, platform), media_type=media_type, headers={'Cache-Control': 'no-store'})
    metadata = installer_parts(platform)
    if metadata:
        if not plan_bundle_ready(plan, platform):
            raise HTTPException(503, "The complete installer is temporarily unavailable.")
        requests = [storage_request(plan, platform=platform, object_name=part["name"]) for part in metadata["parts"]]
        try:
            first = urllib.request.urlopen(requests[0], timeout=30)
        except (HTTPError, OSError, ValueError):
            raise HTTPException(503, "The installer is temporarily unavailable.")
        return StreamingResponse(
            stream_installer_parts(requests, metadata, first),
            media_type=media_type,
            headers={"Cache-Control": "no-store", "Content-Length": str(metadata["size"]),
                     "Content-Disposition": f'attachment; filename="{customer_installer_filename(plan, platform)}"',
                     "ETag": '"' + metadata["sha256"] + '"'},
        )
    storage = storage_request(plan, platform=platform)
    if not storage:
        raise HTTPException(503, 'The release file is temporarily unavailable. Contact AVARA support.')
    try:
        upstream = urllib.request.urlopen(storage, timeout=20)
    except HTTPError as exc:
        logger.warning('Approved order %s release download HTTP %s', order_id, exc.code)
        raise HTTPException(503, 'The release file is temporarily unavailable. Contact AVARA support.')
    except (OSError, ValueError):
        raise HTTPException(503, 'The release file is temporarily unavailable. Contact AVARA support.')

    def stream_release():
        try:
            while chunk := upstream.read(1024 * 1024):
                yield chunk
        finally:
            upstream.close()

    return StreamingResponse(
        stream_release(), media_type=media_type,
        headers={'Cache-Control': 'no-store', 'Content-Disposition': f'attachment; filename="{customer_installer_filename(plan, platform) if installer_downloads() else plan_filename(plan, platform)}"'},
    )

