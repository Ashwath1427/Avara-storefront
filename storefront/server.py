@app.post('/api/admin/order/{order_id}/activate')
def activate_installation(order_id: int, data: ActivationApproval, request: Request):
    actor = owner_session(request)
    edition, _, digits = data.code.strip().upper().partition('-')
    code = digits.replace('-', '')
    if not re.fullmatch(r'[0-9A-F]{32}', code):
        raise HTTPException(400, 'Enter the activation code shown in the customer’s AVARA app.')
    with db() as con:
        activation_table(con)
        con.execute('BEGIN IMMEDIATE')
        order = con.execute('SELECT plan,status,user_id,platform FROM orders WHERE id=? AND deleted_at IS NULL', (order_id,)).fetchone()
        if not order or order[1] != 'approved':
            raise HTTPException(409, 'Only a paid and approved order can activate an installation.')
        plan = plan_slug(order[0])
        if edition not in {'BASIC', 'PRO'}:
            raise HTTPException(409, 'Enter a valid Basic or Pro installation code.')
        term_days = 180 if order[0].startswith(('AVARA 6-Month Plus', '6-Month Basic', '6-Month Pro')) else 30
        expires = int(time.time()) + term_days * 86400
        existing = con.execute(
            '''SELECT installations.order_id,orders.user_id,orders.platform,orders.plan
               FROM installations JOIN orders ON orders.id=installations.order_id
               WHERE installations.code=?''', (code,),
        ).fetchone()
        if existing and existing[0] != order_id:
            if existing[1] != order[2] or existing[2] != order[3]:
                raise HTTPException(409, 'This installation belongs to a different customer or operating system.')
            if con.execute('SELECT 1 FROM installations WHERE order_id=?', (order_id,)).fetchone():
                raise HTTPException(409, 'This order already has an installation.')
            if not data.replace_existing:
                raise HTTPException(409, {
                    'code': 'installation_already_linked',
                    'message': f'This installation is linked to order #{existing[0]} ({existing[3]}). Apply this approved order to the existing installation?',
                    'existing_order_id': existing[0],
                })
            con.execute(
                "UPDATE installations SET order_id=?,plan=?,expires=?,state='active',paused_at=NULL WHERE code=?",
                (order_id, plan, expires, code),
            )
            # The old paid order remains in history but cannot activate a second device.
            con.execute("UPDATE orders SET status='superseded' WHERE id=?", (existing[0],))
            sync_legacy_entitlement(con, code)
            audit(con, actor, 'legacy_installation_replaced', f'order:{order_id}',
                  {'previous_order': existing[0], 'plan': plan, 'term_days': term_days}, client_ip(request))
            return {'message': f'Existing installation updated to AVARA {plan.title()} for {term_days} days using order #{order_id}. The app will refresh at its next license check.'}
        inserted = con.execute(
            'INSERT INTO installations(code,order_id,plan,expires,state,paused_at) VALUES (?,?,?,?,?,?) ON CONFLICT DO NOTHING',
            (code, order_id, plan, expires, 'active', None),
        )
        if not inserted.rowcount:
            raise HTTPException(409, 'This activation code or order has already been used.')
        sync_legacy_entitlement(con, code)
        audit(con, actor, 'legacy_installation_activated', f'order:{order_id}',
              {'plan': plan, 'term_days': term_days}, client_ip(request))
    return {'message': f'AVARA {plan.title()} activated for {term_days} days.'}


@app.post('/api/activation/check')
def check_installation(data: InstallationCheck, response: Response):
    response.headers['Cache-Control'] = 'no-store'
    code = hashlib.sha256(bytes.fromhex(data.token)).hexdigest()[:32].upper()
    with db() as con:
        activation_table(con)
        if licensing_ready(con):
            # Entitlements are the source of truth once migrated; old installed
            # copies keep receiving the same unsigned answer format as before.
            entitlement = con.execute(
                '''SELECT tier, expires_at, state, six_month FROM entitlements
                   WHERE legacy_code=? OR installation_id=? ORDER BY updated_at DESC LIMIT 1''',
                (code, licensing.installation_id(data.token)),
            ).fetchone()
            if entitlement:
                tier, expires, state, six_month = entitlement
                if state != 'active':
                    return {'status': state, 'plan': tier, 'expires': expires}
                if expires <= time.time():
                    return {'status': 'expired'}
                return {'status': 'active', 'plan': tier, 'expires': expires, 'six_month': bool(six_month)}
        row = con.execute(
            '''SELECT installations.plan, installations.expires, installations.state, orders.plan, orders.deleted_at
               FROM installations JOIN orders ON orders.id=installations.order_id
               WHERE installations.code=? AND orders.status='approved' ''', (code,),
        ).fetchone()
    if not row:
        return {'status': 'pending'}
    if row[4] is not None:
        return {'status': 'cancelled', 'plan': row[0], 'expires': row[1]}
    if row[2] != 'active':
        return {'status': row[2], 'plan': row[0], 'expires': row[1]}
    if row[1] <= time.time():
        return {'status': 'expired'}
    return {'status': 'active', 'plan': row[0], 'expires': row[1],
            'six_month': row[3].startswith(('6-Month Basic', '6-Month Pro', 'AVARA 6-Month Plus'))}


@app.post('/api/admin/order/{order_id}/subscription')
def change_subscription(order_id: int, data: SubscriptionChange, request: Request):
    actor = owner_session(request)
    now = int(time.time())
    with db() as con:
        activation_table(con)
        if not con.execute('SELECT 1 FROM orders WHERE id=? AND deleted_at IS NULL', (order_id,)).fetchone():
            raise HTTPException(404, 'Order not found. Restore deleted orders before changing them.')
        row = con.execute(
            'SELECT plan,expires,state,paused_at FROM installations WHERE order_id=?', (order_id,),
        ).fetchone()
        if not row:
            raise HTTPException(409, 'Activate this installation before changing its subscription.')
        plan, expires, state, paused_at = row
        if data.action == 'pause':
            if state == 'active':
                con.execute("UPDATE installations SET state='paused',paused_at=? WHERE order_id=?", (now, order_id))
            message = 'Installation paused. AVARA will lock at its next online license check.'
        elif data.action == 'resume':
            extension = max(0, now - paused_at) if state in {'paused', 'cancelled'} and paused_at else 0
            con.execute(
                "UPDATE installations SET state='active',paused_at=NULL,expires=? WHERE order_id=?",
                (expires + extension, order_id),
            )
            message = 'Installation resumed.'
        elif data.action == 'cancel':
            con.execute("UPDATE installations SET state='cancelled',paused_at=? WHERE order_id=?", (now, order_id))
            message = 'Installation cancelled. AVARA will lock at its next online license check.'
        elif data.action == 'change_plan':
            if not data.plan:
                raise HTTPException(400, 'Choose Basic, Pro, or 6-Month Plus.')
            entitlement = 'pro' if data.plan in {'pro', 'six_month_plus', 'six_month_pro'} else 'basic'
            display_plan = {
                'basic': 'Basic — ₹150/month',
                'pro': 'Pro — ₹200/month',
                'six_month_plus': 'AVARA 6-Month Plus — ₹1,000/6 months',
                'six_month_basic': '6-Month Basic — ₹1,000/6 months',
                'six_month_pro': '6-Month Pro — ₹1,400/6 months',
            }[data.plan]
            if data.plan in {'six_month_plus', 'six_month_basic', 'six_month_pro'}:
                expires = max(expires, now + 180 * 86400)
            con.execute('UPDATE installations SET plan=?,expires=? WHERE order_id=?', (entitlement, expires, order_id))
            con.execute('UPDATE orders SET plan=? WHERE id=?', (display_plan, order_id))
            message = f'Installation changed to {display_plan}.'
        else:
            new_expiry = max(now, expires) + 30 * 86400
            con.execute('UPDATE installations SET expires=? WHERE order_id=?', (new_expiry, order_id))
            message = 'Activation extended by 30 days.'
        sync_legacy_order(con, order_id)
        audit(con, actor, 'legacy_subscription_' + data.action, f'order:{order_id}', {'plan': data.plan}, client_ip(request))
    return {'message': message}


